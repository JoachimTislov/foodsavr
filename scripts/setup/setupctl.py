#!/usr/bin/env python3
"""Idempotent, fork-safe FoodSavr setup engine (ADR 0008).

Philosophy: humans make decisions, agents make it possible.

Read-only / local-only subcommands (safe for agents):
  - ``probe``          Inspect local tools, git remotes, GitHub repo permissions,
                       existing branches/vars/secrets (names only), and local stubs.
  - ``plan``           Compute an ordered setup plan split into ``agent_actions``
                       and ``human_actions`` (plus optional generated ``.tfvars``).
  - ``scaffold-local`` Idempotently scaffold local-dev stubs (``firebase_options.dart``,
                       ``assets/.env``, ``google-services.json``, ``.agents/instance.local.json``)
                       and git hooks without overwriting existing real config.
  - ``verify``         Verify every prerequisite for the chosen profile.

Mutating GitHub subcommands (human-executed only; refuse unattended agent envs):
  - ``fork``           Fork upstream safely with explicit ``--remote=true`` and
                       ``gh repo set-default``.
  - ``ensure-branches`` Create missing channel branches via GitHub Refs API
                       (never deletes branches on topology downgrade).
  - ``wizard``         Interactive terminal menu (used by ``make setup``).
"""

