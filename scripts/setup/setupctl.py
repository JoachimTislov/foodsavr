REPO_SLUG_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")


def _run(
    argv: list[str],
    *,
    cwd: Path | None = None,
    timeout: int = 15,
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            argv,
            cwd=str(cwd or ROOT),
            text=True,
            capture_output=True,
            timeout=timeout,
            check=False,
        )
    except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
        return subprocess.CompletedProcess(argv, 127, "", str(exc))


def parse_github_repo(remote_url: str) -> str | None:
    match = GITHUB_URL_RE.match(remote_url.strip())
    return match.group(1) if match else None


def is_unattended_agent_env(env: dict[str, str] | None = None) -> bool:
    source = os.environ if env is None else env
    return any(bool(source.get(key)) for key in AGENT_ENV_VARS)


def load_instance_local(root: Path = ROOT) -> dict[str, Any]:
    return instance_local.load(root)


def save_instance_local(payload: dict[str, Any], root: Path = ROOT) -> Path:
    path = instance_local.path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    merged = {**load_instance_local(root), **payload, "updated_at": datetime.now(timezone.utc).isoformat()}
    with NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as temporary:
        json.dump(merged, temporary, indent=2, sort_keys=True)
        temporary.write("\n")
    Path(temporary.name).replace(path)
    return path


def detect_git_remotes(root: Path = ROOT) -> dict[str, str]:
    proc = _run(["git", "remote", "-v"], cwd=root)
    if proc.returncode != 0:
        return {}
    remotes: dict[str, str] = {}
    for line in proc.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] not in remotes:
            remotes[parts[0]] = parts[1]
    return remotes


def probe_environment(
    *,
    repo: str | None = None,
    root: Path = ROOT,
    offline: bool = False,
) -> dict[str, Any]:
    """Read-only probe of local tools, git remotes, local stubs, and GitHub state."""
    tool_names = ("git", "gh", "terraform", "flutter", "dart", "gcloud", "python3", "claude", "codex", "agy")
    tools = {name: shutil.which(name) is not None for name in tool_names}

    remotes = detect_git_remotes(root)
    origin_repo = parse_github_repo(remotes.get("origin", ""))
    upstream_repo = parse_github_repo(remotes.get("upstream", ""))
    local_cfg = load_instance_local(root)
    target_repo = repo or local_cfg.get("repo") or origin_repo

    hooks_proc = _run(["git", "config", "--get", "core.hooksPath"], cwd=root)
    hooks_path = hooks_proc.stdout.strip() if hooks_proc.returncode == 0 else ""

    local_files = {
        "dotenv": (root / "assets/.env").is_file(),
        "google_services": (root / "android/app/google-services.json").is_file(),
        "instance_local": instance_local.path(root).is_file(),
        "hooks_configured": hooks_path == ".githooks",
    }

    gh_info: dict[str, Any] = {
        "authenticated": False,
        "login": None,
        "target_repo": target_repo,
        "repo_accessible": False,
        "is_admin": False,
        "private": None,
        "default_branch": None,
        "rulesets_supported": None,
        "needs_fork": False,
        "is_fork": False,
        "config_readable": False,
        "branches": [],
        "variables": {},
        "secret_names": [],
        "event_policy": None,
    }

    if not offline and tools["gh"]:
        user_proc = _run(["gh", "api", "user", "--jq", ".login"], cwd=root)
        if user_proc.returncode == 0 and user_proc.stdout.strip():
            gh_info["authenticated"] = True
            gh_info["login"] = user_proc.stdout.strip()

        if gh_info["authenticated"] and target_repo and REPO_SLUG_RE.fullmatch(target_repo):
            repo_proc = _run(["gh", "api", f"repos/{target_repo}"], cwd=root)
            if repo_proc.returncode == 0:
                try:
                    repo_json = json.loads(repo_proc.stdout)
                except ValueError:
                    repo_json = {}
                perms = repo_json.get("permissions") or {}
                gh_info["repo_accessible"] = True
                gh_info["is_admin"] = bool(perms.get("admin"))
                gh_info["private"] = bool(repo_json.get("private"))
                gh_info["default_branch"] = repo_json.get("default_branch")
                gh_info["is_fork"] = bool(repo_json.get("fork"))
                gh_info["needs_fork"] = not gh_info["is_admin"]

                # Ruleset availability check (private repos on GitHub Free return 403/404)
                if gh_info["private"]:
                    rs_proc = _run(["gh", "api", f"repos/{target_repo}/rulesets"], cwd=root)
                    gh_info["rulesets_supported"] = rs_proc.returncode == 0
                else:
                    gh_info["rulesets_supported"] = True

                br_proc = _run(
                    ["gh", "api", f"repos/{target_repo}/branches?per_page=100", "--paginate", "--jq", ".[].name"],
                    cwd=root,
                )
                if br_proc.returncode == 0:
                    gh_info["branches"] = sorted(line.strip() for line in br_proc.stdout.splitlines() if line.strip())

                if gh_info["is_admin"]:
                    gh_info["event_policy"] = read_event_policy(target_repo, root=root)
                    var_proc = _run(
                        ["gh", "variable", "list", "--repo", target_repo, "--json", "name,value"],
                        cwd=root,
                    )
                    if var_proc.returncode == 0:
                        try:
                            gh_info["variables"] = {
                                item["name"]: item["value"]
                                for item in json.loads(var_proc.stdout)
                                if isinstance(item, dict) and "name" in item
                            }
                        except ValueError:
                            pass

                    sec_proc = _run(
                        ["gh", "secret", "list", "--repo", target_repo, "--json", "name"],
                        cwd=root,
                    )
                    gh_info["config_readable"] = var_proc.returncode == sec_proc.returncode == 0
                    if sec_proc.returncode == 0:
                        try:
                            gh_info["secret_names"] = sorted(
                                item["name"]
                                for item in json.loads(sec_proc.stdout)
                                if isinstance(item, dict) and "name" in item
                            )
                        except ValueError:
                            pass

    recommended_topology = (
        "full-channels" if target_repo == UPSTREAM_REPO and gh_info.get("is_admin") else "single"
    )
    return {
        "schema_version": 1,
        "root": str(root),
        "tools": tools,
        "remotes": remotes,
        "origin_repo": origin_repo,
        "upstream_repo": upstream_repo,
        "local_config": local_cfg,
        "local_files": local_files,
        "github": gh_info,
        "recommendations": {
            "default_topology": recommended_topology,
            "enable_rulesets": bool(gh_info["rulesets_supported"]) if gh_info["rulesets_supported"] is not None else True,
        },
    }


def build_plan(
    probe: dict[str, Any],
    *,
    profile: str,
    topology: str | None = None,
    firebase_plan: str = "spark",
    repo: str | None = None,
    write_dir: Path | None = None,
) -> dict[str, Any]:
    """Build an ADR 0003/0008 setup plan separated into agent and human actions."""
    if profile not in PROFILES:
        raise ValueError(f"Unsupported profile: {profile!r}")
    if firebase_plan not in FIREBASE_PLANS:
        raise ValueError(f"Unsupported firebase_plan: {firebase_plan!r}")

    gh = probe["github"]
    target_repo = repo or gh.get("target_repo") or UPSTREAM_REPO
    chosen_topology = topology or probe["recommendations"]["default_topology"]
    if chosen_topology not in TOPOLOGIES:
        raise ValueError(f"Unsupported topology: {chosen_topology!r}")

    login = gh.get("login")
    needs_fork = profile != "local-dev" and bool(gh.get("needs_fork"))
    effective_repo = f"{login}/{target_repo.split('/', 1)[1]}" if (needs_fork and login and "/" in target_repo) else target_repo

    agent_actions: list[dict[str, Any]] = []
    human_actions: list[dict[str, Any]] = []
    blockers: list[str] = []

    # 1. Local development scaffold (always safe for agents)
    local_files = probe["local_files"]
    if not all(local_files.values()):
        agent_actions.append({
            "id": "scaffold-local",
            "title": "Scaffold gitignored local-dev files and .githooks",
            "command": (
                f"python3 scripts/setup/setupctl.py scaffold-local "
                f"--profile {profile} --topology {chosen_topology} --repo {effective_repo}"
            ),
        })

    if profile == "local-dev":
        if not probe["tools"].get("flutter"):
            blockers.append("Install Flutter SDK before running the app locally.")
        return {
            "profile": profile,
            "topology": chosen_topology,
            "target_repo": effective_repo,
            "needs_fork": False,
            "blockers": blockers,
            "agent_actions": agent_actions,
            "human_actions": human_actions,
            "generated_files": [],
        }

    # Profiles requiring GitHub ownership (fork-agents / full-cloud)
    if not probe["tools"].get("gh"):
        blockers.append("Install GitHub CLI (`gh`) and run `gh auth login`.")
    elif not gh.get("authenticated"):
        human_actions.append({
            "id": "gh-login",
            "title": "Authenticate GitHub CLI",
            "command": "gh auth login",
            "reason": "Required to inspect/configure your repository and run GitHub Terraform.",
        })

    if not probe["tools"].get("terraform"):
        blockers.append("Install Terraform >= 1.7 (https://developer.hashicorp.com/terraform/install).")

    if needs_fork:
        human_actions.append({
            "id": "fork-repo",
            "title": f"Fork {target_repo} to your GitHub account ({effective_repo})",
            "command": f"python3 scripts/setup/setupctl.py fork --upstream {target_repo} --yes",
            "reason": "Non-owners cannot configure Secrets or Actions on upstream; fork safely sets origin + upstream + gh default.",
        })

    # Channel branches via GitHub Refs API (never managed by Terraform github_branch)
    required_branches = TOPOLOGY_BRANCHES[chosen_topology]
    existing_branches = set(gh.get("branches") or [])
    missing_branches = [b for b in required_branches if b not in existing_branches]
    if missing_branches or needs_fork:
        human_actions.append({
            "id": "ensure-branches",
            "title": f"Create missing channel branches ({', '.join(missing_branches or required_branches)})",
            "command": (
                f"python3 scripts/setup/setupctl.py ensure-branches "
                f"--repo {effective_repo} --topology {chosen_topology} --yes"
            ),
            "reason": "Creates channel branches idempotently via GitHub Refs API before rulesets apply.",
        })

    secrets_present = set(gh.get("secret_names") or [])
    vars_present = gh.get("variables") or {}

    has_agent_app = ("AGENT_APP_PRIVATE_KEY" in secrets_present) and (
        "AGENT_APP_ID" in vars_present or "AGENT_APP_ID" in secrets_present
    )
    if not has_agent_app or needs_fork:
        human_actions.append({
            "id": "create-agent-app",
            "title": "Create untrusted author GitHub App",
            "command": f"scripts/human/github/create-agent-app.sh --role agent --repo {effective_repo}",
            "reason": "Used by agent-ops.yml (implement); no workflows:write or ruleset bypass.",
        })

    has_release_gate_app = (
        ("RELEASE_GATE_APP_PRIVATE_KEY" in secrets_present)
        and ("RELEASE_GATE_APP_ID" in vars_present or "RELEASE_GATE_APP_ID" in secrets_present)
    )
    if not has_release_gate_app or needs_fork:
        human_actions.append({
            "id": "create-release-gate-app",
            "title": "Create trusted Release-Gate GitHub App",
            "command": f"scripts/human/github/create-agent-app.sh --role release-gate --repo {effective_repo}",
            "reason": "Used by merge-gate.yml and release.yml (promote); sole app allowed on the PR-gate ruleset bypass.",
        })

    has_harness_auth = any(name in secrets_present for name in HARNESS_AUTH_SECRETS)
    if not has_harness_auth or needs_fork:
        human_actions.append({
            "id": "sync-harness-auth",
            "title": "Push at least one CI agent harness login secret",
            "command": (
                f"scripts/secrets/rotate.py --repo {effective_repo} CLAUDE_CODE_OAUTH_TOKEN "
                f"# or CODEX_AUTH_JSON_B64 / ANTIGRAVITY_OAUTH_TOKEN_B64 / GEMINI_API_KEY"
            ),
            "reason": "CI runs harnesses directly with quota-aware routing (ADR 0008); add 2+ for automatic failover.",
        })

    owner, repo_name = effective_repo.split("/", 1) if "/" in effective_repo else ("<owner>", effective_repo)
    enable_rulesets = bool(probe["recommendations"].get("enable_rulesets", True))
    generated_files: list[str] = []
    tfvars_arg = ""
    if write_dir is not None:
        write_dir.mkdir(parents=True, exist_ok=True)
        github_tfvars = write_dir / "github.tfvars"
        github_tfvars.write_text(
            render_github_tfvars(
                owner=owner,
                repo=repo_name,
                topology=chosen_topology,
                enable_rulesets=enable_rulesets,
                agent_app_id=str(vars_present.get("AGENT_APP_ID", "")),
                release_gate_app_id=int(vars_present["RELEASE_GATE_APP_ID"])
                if str(vars_present.get("RELEASE_GATE_APP_ID", "")).isdigit()
                else 0,
            ),
            encoding="utf-8",
        )
        generated_files.append(str(github_tfvars))
        tfvars_arg = f" TFVARS_FILE={github_tfvars}"

    agent_actions.append({
        "id": "plan-github-terraform",
        "title": "Preview repository GitHub Terraform plan (read-only)",
        "command": (
            f"GITHUB_REPOSITORY={effective_repo} RELEASE_TOPOLOGY={chosen_topology}{tfvars_arg} "
            "scripts/infra/apply-github.sh plan"
        ),
    })
    human_actions.append({
        "id": "apply-github-terraform",
        "title": "Apply GitHub rulesets, environments, labels, and non-secret variables",
        "command": (
            f"GITHUB_REPOSITORY={effective_repo} RELEASE_TOPOLOGY={chosen_topology}{tfvars_arg} "
            "scripts/infra/apply-github.sh apply"
        ),
        "reason": "Declaratively converges split rulesets, production environment branch pin, and RELEASE_TOPOLOGY.",
    })

    if profile == "full-cloud":
        if not probe["tools"].get("gcloud"):
            blockers.append("Install Google Cloud CLI (`gcloud`) and run `gcloud auth login`.")
        agent_actions.append({
            "id": "plan-gcp-terraform",
            "title": "Preview GCP/Firebase Terraform plan (read-only)",
            "command": f"ENV=production RELEASE_TOPOLOGY={chosen_topology} scripts/infra/apply.sh plan",
        })
        human_actions.append({
            "id": "apply-gcp-terraform",
            "title": f"Apply GCP/Firebase stack (WIF + App Check, plan={firebase_plan})",
            "command": f"ENV=production RELEASE_TOPOLOGY={chosen_topology} scripts/infra/apply.sh apply",
            "reason": "Provisions scoped github-deploy-live and github-telemetry-ro WIF service accounts and publishes non-secret vars.",
        })

    event_policy = gh.get("event_policy") or {}
    if event_policy.get("state") != "match":
        human_actions.append({
            "id": "apply-event-policy",
            "title": "Record the Actions event policy allowing pull_request_target for the three trusted workflows",
            "command": f"make setup-event-policy REPO={effective_repo}",
            "reason": "GitHub blocks pull_request_target in public repositories from 2026-12-02 without an explicit policy.",
        })

    if needs_fork:
        human_actions.append({
            "id": "enable-actions",
            "title": "Enable GitHub Actions on the fork (after vars and secrets are ready)",
            "command": f"gh api -X PUT repos/{effective_repo}/actions/permissions -F enabled=true",
            "reason": "Prevents scheduled cron failures before credentials are configured.",
        })

    return {
        "profile": profile,
        "topology": chosen_topology,
        "firebase_plan": firebase_plan if profile == "full-cloud" else None,
        "target_repo": effective_repo,
        "needs_fork": needs_fork,
        "enable_rulesets": enable_rulesets,
        "blockers": blockers,
        "agent_actions": agent_actions,
        "human_actions": human_actions,
        "generated_files": generated_files,
    }


def render_github_tfvars(
    *,
    owner: str,
    repo: str,
    topology: str,
    enable_rulesets: bool,
    agent_app_id: str = "",
    release_gate_app_id: int = 0,
) -> str:
    lines = [
        "# Generated by scripts/setup/setupctl.py (non-secret values only; ADR 0008).",
        f"github_owner        = {json.dumps(owner)}",
        f"github_repository   = {json.dumps(repo)}",
        f"release_topology    = {json.dumps(topology)}",
        f"enable_rulesets     = {'true' if enable_rulesets else 'false'}",
    ]
    if agent_app_id:
        lines.append(f"agent_app_id        = {json.dumps(agent_app_id)}")
    if release_gate_app_id > 0:
        lines.append(f"release_gate_app_id = {release_gate_app_id}")
    return "\n".join(lines) + "\n"


def scaffold_local(
    *,
    root: Path = ROOT,
    profile: str = "local-dev",
    topology: str = "single",
    repo: str | None = None,
    force: bool = False,
) -> dict[str, Any]:
    """Idempotently create gitignored local-dev stubs and configure git hooks."""
    created: list[str] = []
    skipped: list[str] = []

    targets = [
        (root / "assets/.env", DOTENV_STUB),
        (root / "android/app/google-services.json", json.dumps(GOOGLE_SERVICES_STUB, indent=2) + "\n"),
    ]
    for path, content in targets:
        if path.exists() and not force:
            skipped.append(str(path.relative_to(root)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(str(path.relative_to(root)))

    hooks_proc = _run(["git", "config", "core.hooksPath", ".githooks"], cwd=root)
    hooks_updated = hooks_proc.returncode == 0

    instance_payload: dict[str, Any] = {
        "schema_version": 1,
        "profile": profile,
        "release_topology": topology,
    }
    if repo:
        instance_payload["repo"] = repo
    instance_path = save_instance_local(instance_payload, root=root)

    return {
        "created": created,
        "skipped": skipped,
        "hooks_configured": hooks_updated,
        "instance_local": str(instance_path.relative_to(root)),
    }


def ensure_branches(
    *,
    repo: str,
    topology: str,
    default_branch: str = "develop",
    dry_run: bool = False,
    root: Path = ROOT,
) -> dict[str, Any]:
    """Idempotently create missing channel branches via GitHub Refs API (never deletes)."""
    if not REPO_SLUG_RE.fullmatch(repo):
        raise ValueError(f"Invalid repo slug: {repo!r}")
    if topology not in TOPOLOGIES:
        raise ValueError(f"Unsupported topology: {topology!r}")
    if not dry_run and is_unattended_agent_env():
        raise PermissionError("Refusing GitHub branch mutation from an unattended agent environment; run interactively.")

    ref_proc = _run(["gh", "api", f"repos/{repo}/git/ref/heads/{default_branch}", "--jq", ".object.sha"], cwd=root)
    if ref_proc.returncode != 0 or not ref_proc.stdout.strip():
        raise RuntimeError(f"Cannot resolve default branch '{default_branch}' on {repo}: {ref_proc.stderr.strip()}")
    base_sha = ref_proc.stdout.strip()

    br_proc = _run(
        ["gh", "api", "--paginate", f"repos/{repo}/branches?per_page=100",
         "--jq", '.[] | [.name, .commit.sha] | @tsv'],
        cwd=root,
    )
    if br_proc.returncode != 0:
        raise RuntimeError(f"Cannot list branches on {repo}: {br_proc.stderr.strip()}")
    existing = dict(line.split("\t", 1) for line in br_proc.stdout.splitlines() if line)
    legacy = {"daily": "nightly", "weekly": "beta"}
    stable_sha = existing.get("stable")

    def compare(ancestor: str, descendant: str) -> str:
        if ancestor == descendant:
            return "identical"
        result = _run(
            ["gh", "api", f"repos/{repo}/compare/{ancestor}...{descendant}", "--jq", ".status"],
            cwd=root,
        )
        if result.returncode != 0:
            raise RuntimeError(f"Cannot compare {ancestor} and {descendant}: {result.stderr.strip()}")
        return result.stdout.strip()

    def includes(descendant: str, ancestor: str) -> bool:
        return compare(ancestor, descendant) in {"ahead", "identical"}

    required = [b for b in TOPOLOGY_BRANCHES[topology] if b != default_branch]
    created: list[str] = []
    already_present: list[str] = []
    seeds: dict[str, dict[str, str]] = {}
    for branch in required:
        if branch in existing:
            already_present.append(branch)
            continue

        seed = default_branch
        sha = base_sha
        old_branch = legacy.get(branch)
        old_sha = existing.get(old_branch) if old_branch else None
        if (old_sha and includes(base_sha, old_sha)
                and (not stable_sha or includes(old_sha, stable_sha))):
            seed, sha = old_branch, old_sha
        if branch == "weekly" and seed == "beta":
            daily_sha = existing.get("daily") or seeds.get("daily", {}).get("sha")
            if daily_sha and compare(daily_sha, sha) == "diverged":
                seed, sha = default_branch, base_sha
        if branch == "stable" and topology == "full-channels":
            sha = existing.get("weekly") or seeds["weekly"]["sha"]
            seed = "weekly"

        if not dry_run:
            post_proc = _run(
                ["gh", "api", "-X", "POST", f"repos/{repo}/git/refs",
                 "-f", f"ref=refs/heads/{branch}", "-f", f"sha={sha}"],
                cwd=root,
            )
            if post_proc.returncode != 0:
                # A concurrent setup may have created this ref since the listing.
                ref = _run(["gh", "api", f"repos/{repo}/git/ref/heads/{branch}",
                            "--jq", ".object.sha"], cwd=root)
                if ref.returncode != 0 or not ref.stdout.strip():
                    raise RuntimeError(f"Failed creating branch '{branch}' on {repo}: {post_proc.stderr.strip()}")
                existing[branch] = ref.stdout.strip()
                already_present.append(branch)
                continue
        created.append(branch)
        seeds[branch] = {"source": seed, "sha": sha}

    return {
        "repo": repo,
        "topology": topology,
        "base_branch": default_branch,
        "base_sha": base_sha,
        "created": created,
        "already_present": already_present,
        "seeds": seeds,
        "legacy_present": sorted(existing.keys() & {"nightly", "beta", "release"}),
        "dry_run": dry_run,
    }


def fork_repository(
    *,
    upstream: str = UPSTREAM_REPO,
    dry_run: bool = False,
    root: Path = ROOT,
) -> dict[str, Any]:
    """Safely fork upstream, configure origin/upstream remotes, and set gh default repo."""
    if not REPO_SLUG_RE.fullmatch(upstream):
        raise ValueError(f"Invalid upstream repo slug: {upstream!r}")
    if not dry_run and is_unattended_agent_env():
        raise PermissionError("Refusing to fork repository from an unattended agent environment; run interactively.")

    user_proc = _run(["gh", "api", "user", "--jq", ".login"], cwd=root)
    if user_proc.returncode != 0 or not user_proc.stdout.strip():
        raise RuntimeError("gh is not authenticated; run `gh auth login` first.")
    login = user_proc.stdout.strip()
    repo_name = upstream.split("/", 1)[1]
    fork_slug = f"{login}/{repo_name}"

    commands = [
        ["gh", "repo", "fork", upstream, "--clone=false", "--remote=true", "--default-branch-only=false"],
        ["gh", "repo", "set-default", fork_slug],
    ]
    if dry_run:
        return {"upstream": upstream, "fork": fork_slug, "commands": [" ".join(c) for c in commands], "dry_run": True}

    for cmd in commands:
        proc = _run(cmd, cwd=root, timeout=60)
        if proc.returncode != 0:
            raise RuntimeError(f"Command failed ({' '.join(cmd)}): {proc.stderr.strip()}")

    save_instance_local({"repo": fork_slug, "upstream": upstream}, root=root)
    return {"upstream": upstream, "fork": fork_slug, "commands": [" ".join(c) for c in commands], "dry_run": False}


def resolve_repo(repo: str | None = None, *, root: Path = ROOT) -> str:
    if repo:
        if not REPO_SLUG_RE.fullmatch(repo):
            raise ValueError(f"Invalid repo slug: {repo!r}")
        return repo
    remotes = detect_git_remotes(root)
    origin_repo = parse_github_repo(remotes.get("origin", ""))
    if origin_repo and REPO_SLUG_RE.fullmatch(origin_repo):
        return origin_repo
    local_repo = load_instance_local(root).get("repo")
    if isinstance(local_repo, str) and REPO_SLUG_RE.fullmatch(local_repo):
        return local_repo
    raise ValueError("Cannot determine repository from origin remote; pass --repo <owner>/<repo>.")


def resolve_topology(repo: str, topology: str | None = None, *, root: Path = ROOT) -> str:
    if topology:
        if topology not in TOPOLOGIES:
            raise ValueError(f"Unsupported topology: {topology!r}")
        return topology
    var_proc = _run(["gh", "api", f"repos/{repo}/actions/variables/RELEASE_TOPOLOGY", "--jq", ".value"], cwd=root)
    candidate = var_proc.stdout.strip() if var_proc.returncode == 0 else ""
    if candidate in TOPOLOGIES:
        return candidate
    return "full-channels"


def resolve_upstream(upstream: str | None = None, *, root: Path = ROOT) -> str:
    if upstream:
        if not REPO_SLUG_RE.fullmatch(upstream):
            raise ValueError(f"Invalid upstream repo slug: {upstream!r}")
        return upstream
    remotes = detect_git_remotes(root)
    upstream_repo = parse_github_repo(remotes.get("upstream", ""))
    if upstream_repo and REPO_SLUG_RE.fullmatch(upstream_repo):
        return upstream_repo
    origin_repo = parse_github_repo(remotes.get("origin", ""))
    if origin_repo and origin_repo.casefold() != UPSTREAM_REPO.casefold():
        parent_proc = _run(["gh", "api", f"repos/{origin_repo}", "--jq", ".parent.full_name // empty"], cwd=root)
        parent = parent_proc.stdout.strip() if parent_proc.returncode == 0 else ""
        if parent and REPO_SLUG_RE.fullmatch(parent):
            return parent
    return UPSTREAM_REPO


def enable_actions(
    *,
    repo: str,
    dry_run: bool = False,
    root: Path = ROOT,
) -> dict[str, Any]:
    """Idempotently enable GitHub Actions on a repository."""
    if not REPO_SLUG_RE.fullmatch(repo):
        raise ValueError(f"Invalid repo slug: {repo!r}")
    if not dry_run and is_unattended_agent_env():
        raise PermissionError("Refusing GitHub Actions mutation from an unattended agent environment; run interactively.")

    get_proc = _run(["gh", "api", f"repos/{repo}/actions/permissions", "--jq", ".enabled"], cwd=root)
    if get_proc.returncode != 0:
        raise RuntimeError(f"Cannot read Actions permissions on {repo}: {get_proc.stderr.strip()}")
    already_enabled = get_proc.stdout.strip().lower() == "true"
    if already_enabled or dry_run:
        return {"repo": repo, "enabled": True, "already_enabled": already_enabled, "dry_run": dry_run}

    put_proc = _run(
        ["gh", "api", "-X", "PUT", f"repos/{repo}/actions/permissions", "-F", "enabled=true"],
        cwd=root,
    )
    if put_proc.returncode != 0:
        raise RuntimeError(f"Failed enabling GitHub Actions on {repo}: {put_proc.stderr.strip()}")
    return {"repo": repo, "enabled": True, "already_enabled": False, "dry_run": False}


def desired_event_policy() -> dict[str, Any]:
    """Actions event policy (REST `actions/policies`) allowing pull_request_target for exactly three workflows."""
    return {
        "name": EVENT_POLICY_NAME,
        "enforcement": "active",
        "conditions": {"workflow_path": {"include": list(EVENT_POLICY_WORKFLOWS), "exclude": []}},
        "rules": [{"type": "restrict_action_events", "parameters": {"allowed_events": list(EVENT_POLICY_EVENTS)}}],
    }


def _policy_matches(actual: dict[str, Any]) -> bool:
    want = desired_event_policy()
    try:
        include = sorted(actual["conditions"]["workflow_path"]["include"])
        exclude = list(actual["conditions"]["workflow_path"].get("exclude") or [])
        # Any rule beyond the recorded event rule (an actor restriction, say) is a mismatch.
        rules = list(actual.get("rules") or [])
        events = (
            sorted(rules[0]["parameters"]["allowed_events"])
            if len(rules) == 1 and rules[0].get("type") == "restrict_action_events"
            else None
        )
    except (KeyError, TypeError, AttributeError, IndexError):
        return False
    return (
        actual.get("enforcement") == want["enforcement"]
        and include == sorted(EVENT_POLICY_WORKFLOWS)
        and not exclude
        and events == sorted(EVENT_POLICY_EVENTS)
    )


def _policy_items(payload: Any) -> list[Any]:
    """Flatten a slurped page list (each page a list or a `{"policies": [...]}` object) into policies."""
    items: list[Any] = []
    for page in payload if isinstance(payload, list) else [payload]:
        if isinstance(page, list):
            items.extend(page)
        elif isinstance(page, dict) and "policies" in page:
            items.extend(page.get("policies") or [])
        elif isinstance(page, dict):
            items.append(page)
    return items


def read_event_policy(repo: str, *, root: Path = ROOT) -> dict[str, Any]:
    """Read-only GET of the repository Actions policies; compare with `desired_event_policy`.

    Returns `{"state": "match"|"mismatch"|"missing"|"unavailable", "policy_id": int|None, "detail": str}`.
    """
    if not REPO_SLUG_RE.fullmatch(repo):
        raise ValueError(f"Invalid repo slug: {repo!r}")
    # The collection is paginated (30 per page by default); read every page before reporting `missing`.
    # Repository-level policies only: an inherited policy with the same name must not be selected.
    proc = _run(["gh", "api", f"repos/{repo}/actions/policies?per_page=100&has_parents=false", "--paginate", "--slurp"], cwd=root)
    if proc.returncode != 0:
        return {"state": "unavailable", "policy_id": None, "detail": proc.stderr.strip() or "Actions policies API unavailable"}
    try:
        payload = json.loads(proc.stdout)
    except ValueError:
        return {"state": "unavailable", "policy_id": None, "detail": "unparseable Actions policies response"}
    items = _policy_items(payload)
    found = next((i for i in items if isinstance(i, dict) and i.get("name") == EVENT_POLICY_NAME), None)
    if found is None:
        return {"state": "missing", "policy_id": None, "detail": f"policy {EVENT_POLICY_NAME!r} not configured"}
    if found.get("id") is not None:
        # The list endpoint returns summaries without `conditions`/`rules`; compare the full policy.
        detail_proc = _run(["gh", "api", f"repos/{repo}/actions/policies/{found['id']}"], cwd=root)
        if detail_proc.returncode != 0:
            return {"state": "unavailable", "policy_id": found["id"], "detail": detail_proc.stderr.strip() or "Actions policy detail unavailable"}
        try:
            detail = json.loads(detail_proc.stdout)
        except ValueError:
            return {"state": "unavailable", "policy_id": found["id"], "detail": "unparseable Actions policy detail response"}
        if not isinstance(detail, dict):
            return {"state": "unavailable", "policy_id": found["id"], "detail": "unexpected Actions policy detail response"}
        found = {**found, **detail}
    if not _policy_matches(found):
        return {"state": "mismatch", "policy_id": found.get("id"), "detail": f"policy {EVENT_POLICY_NAME!r} differs from the recorded posture"}
    return {"state": "match", "policy_id": found.get("id"), "detail": f"policy {EVENT_POLICY_NAME!r} matches"}


def apply_event_policy(
    *,
    repo: str,
    dry_run: bool = False,
    root: Path = ROOT,
) -> dict[str, Any]:
    """Idempotently create or update the Actions event policy."""
    if not REPO_SLUG_RE.fullmatch(repo):
        raise ValueError(f"Invalid repo slug: {repo!r}")
    if not dry_run and is_unattended_agent_env():
        raise PermissionError("Refusing GitHub Actions policy mutation from an unattended agent environment; run interactively.")

    current = read_event_policy(repo, root=root)
    if current["state"] == "unavailable":
        raise RuntimeError(f"Cannot read Actions policies on {repo}: {current['detail']}")
    if current["state"] == "match" or dry_run:
        return {"repo": repo, "state": current["state"], "already_applied": current["state"] == "match", "dry_run": dry_run}

    base = f"repos/{repo}/actions/policies"
    if current["state"] == "mismatch" and current["policy_id"] is None:
        raise RuntimeError(f"Actions policy {EVENT_POLICY_NAME!r} on {repo} has no id; update it under Settings -> Actions -> Policies.")
    method, path = ("POST", base) if current["state"] == "missing" else ("PUT", f"{base}/{current['policy_id']}")
    proc = subprocess.run(
        ["gh", "api", "-X", method, path, "--input", "-"],
        input=json.dumps(desired_event_policy()),
        cwd=root,
        text=True,
        capture_output=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"Failed applying Actions event policy on {repo}: {proc.stderr.strip()}")
    return {"repo": repo, "state": "applied", "already_applied": False, "dry_run": False}


def verify_profile(
    probe: dict[str, Any],
    *,
    profile: str,
    topology: str | None = None,
    live: bool = False,
) -> dict[str, Any]:
    """Evaluate scripts/setup/health.toml for the profile (live=True adds network and GitHub run checks)."""
    if profile not in PROFILES:
        raise ValueError(f"Unsupported profile: {profile!r}")
    gh = probe["github"]
    active = topology or (gh.get("variables") or {}).get("RELEASE_TOPOLOGY") or probe["recommendations"]["default_topology"]
    repo = gh.get("target_repo")
    ctx = health.Context(
        probe=probe,
        profile=profile,
        topology=active,
        branches=TOPOLOGY_BRANCHES.get(active, [INTEGRATION_BRANCH]),
        integration_branch=INTEGRATION_BRANCH,
        live=health.Live(repo) if live and repo and gh.get("is_admin") else None,
    )
    return health.evaluate(ctx)


def _print_probe_text(probe: dict[str, Any]) -> None:
    gh = probe["github"]
    print(f"Repository:  {gh.get('target_repo') or '(undetected)'}")
    print(f"GitHub user: {gh.get('login') or '(not logged in)'} (admin={gh.get('is_admin')}, needs_fork={gh.get('needs_fork')})")
    present_tools = [k for k, v in probe["tools"].items() if v]
    missing_tools = [k for k, v in probe["tools"].items() if not v]
    print(f"Tools OK:    {', '.join(present_tools) or 'none'}")
    print(f"Tools miss:  {', '.join(missing_tools) or 'none'}")
    print(f"Local stubs: {probe['local_files']}")
    if gh.get("repo_accessible"):
        print(f"Branches:    {', '.join(gh.get('branches') or []) or 'none'}")
        print(f"Variables:   {', '.join(sorted((gh.get('variables') or {}).keys())) or 'none'}")
        print(f"Secrets:     {', '.join(gh.get('secret_names') or []) or 'none'}")


def _print_plan_text(plan: dict[str, Any]) -> None:
    print(f"Profile:     {plan['profile']}")
    print(f"Target repo: {plan['target_repo']} (needs_fork={plan['needs_fork']})")
    print(f"Topology:    {plan['topology']}")
    if plan["blockers"]:
        print("\nBlockers:")
        for b in plan["blockers"]:
            print(f"  - {b}")
    print("\nAgent-executable steps (safe local / read-only):")
    for step in plan["agent_actions"]:
        print(f"  [{step['id']}] {step['title']}\n      {step['command']}")
    if not plan["agent_actions"]:
        print("  (none)")
    print("\nHuman-executed steps (irreversible / credentials):")
    for step in plan["human_actions"]:
        print(f"  [{step['id']}] {step['title']}\n      {step['command']}")
    if not plan["human_actions"]:
        print("  (none)")


def _print_verify_text(report: dict[str, Any]) -> None:
    status = "READY" if report["ready"] else "INCOMPLETE"
    print(f"Profile '{report['profile']}': {status}")
    for chk in report["checks"]:
        mark = "OK  " if chk["ok"] else "MISS"
        print(f"  [{mark}] {chk['name']}: {chk['detail']}")
        if not chk["ok"] and chk["remediation"]:
            print(f"         Fix: {chk['remediation']}")
    for note in report.get("notes", []):
        print(f"  [NOTE] {note}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    p_probe = sub.add_parser("probe", help="Read-only environment & GitHub probe")
    p_probe.add_argument("--repo", default=None)
    p_probe.add_argument("--offline", action="store_true")
    p_probe.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_plan = sub.add_parser("plan", help="Compute agent/human setup plan")
    p_plan.add_argument("--profile", choices=PROFILES, required=True)
    p_plan.add_argument("--topology", choices=TOPOLOGIES, default=None)
    p_plan.add_argument("--firebase-plan", choices=FIREBASE_PLANS, default="spark")
    p_plan.add_argument("--repo", default=None)
    p_plan.add_argument("--offline", action="store_true")
    p_plan.add_argument("--write-dir", default=None, help="Optional directory to write generated non-secret .tfvars")
    p_plan.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_scaffold = sub.add_parser("scaffold-local", help="Idempotently scaffold local-dev files and git hooks")
    p_scaffold.add_argument("--profile", choices=PROFILES, default="local-dev")
    p_scaffold.add_argument("--topology", choices=TOPOLOGIES, default="single")
    p_scaffold.add_argument("--repo", default=None)
    p_scaffold.add_argument("--force", action="store_true")
    p_scaffold.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_branches = sub.add_parser("ensure-branches", help="Create missing channel branches via GitHub Refs API")
    p_branches.add_argument("--repo", default=None)
    p_branches.add_argument("--topology", choices=TOPOLOGIES, default=None)
    p_branches.add_argument("--default-branch", default="develop")
    p_branches.add_argument("--dry-run", action="store_true")
    p_branches.add_argument("--yes", action="store_true")
    p_branches.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_fork = sub.add_parser("fork", help="Fork upstream safely and wire remotes + gh default")
    p_fork.add_argument("--upstream", default=None)
    p_fork.add_argument("--dry-run", action="store_true")
    p_fork.add_argument("--yes", action="store_true")
    p_fork.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_actions = sub.add_parser("enable-actions", help="Enable GitHub Actions on a repository")
    p_actions.add_argument("--repo", default=None)
    p_actions.add_argument("--dry-run", action="store_true")
    p_actions.add_argument("--yes", action="store_true")
    p_actions.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_policy = sub.add_parser("apply-event-policy", help="Record the Actions event policy for pull_request_target")
    p_policy.add_argument("--repo", default=None)
    p_policy.add_argument("--dry-run", action="store_true")
    p_policy.add_argument("--yes", action="store_true")
    p_policy.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_verify = sub.add_parser("verify", help="Verify setup readiness for a profile")
    p_verify.add_argument("--profile", choices=PROFILES, required=True)
    p_verify.add_argument("--topology", choices=TOPOLOGIES, default=None)
    p_verify.add_argument("--repo", default=None)
    p_verify.add_argument("--offline", action="store_true")
    p_verify.add_argument("-o", "--output", choices=("text", "json"), default="text")

    p_topology = sub.add_parser("topology", help="Print ordered release branches as JSON")
    p_topology.add_argument("name", choices=TOPOLOGIES)

    p_wizard = sub.add_parser("wizard", help="Interactive human terminal setup menu (make setup)")
    p_wizard.add_argument("--repo", default=None)
    p_wizard.add_argument("--profile", choices=PROFILES)
    p_wizard.add_argument("--list", action="store_true", help="List incomplete steps without changing setup")

    def confirm_interactive(prompt: str, *, yes: bool) -> bool | None:
        if yes:
            return True
        if is_unattended_agent_env() or not sys.stdin.isatty():
            return None
        print(f"{prompt} [y/N]: ", end="", file=interactive_output, flush=True)
        reply = input().strip().lower()
        return reply in {"y", "yes"}

    def format_branches_summary(res: dict[str, Any], *, dry_run: bool) -> str:
        if not res["created"]:
            present = ", ".join(res["already_present"]) or res["base_branch"]
            return f"{res['repo']} ({res['topology']}): release channels ready ({present})."
        details = ", ".join(f"{b} (from {res['seeds'][b]['source']})" for b in res["created"])
        verb = "Would create" if dry_run else "Created"
        return f"{res['repo']} ({res['topology']}): {verb} {details}"

    args = parser.parse_args(argv)
    interactive_output = sys.stderr if getattr(args, "output", None) == "json" else sys.stdout
    try:
        if args.command == "probe":
            result = probe_environment(repo=args.repo, offline=args.offline)
            if args.output == "json":
                print(json.dumps(result, indent=2, sort_keys=True))
            else:
                _print_probe_text(result)
            return 0

        if args.command == "plan":
            probe = probe_environment(repo=args.repo, offline=args.offline)
            write_dir = Path(args.write_dir) if args.write_dir else None
            plan = build_plan(
                probe,
                profile=args.profile,
                topology=args.topology,
                firebase_plan=args.firebase_plan,
                repo=args.repo,
                write_dir=write_dir,
            )
            if args.output == "json":
                print(json.dumps(plan, indent=2, sort_keys=True))
            else:
                _print_plan_text(plan)
            return 0

        if args.command == "scaffold-local":
            res = scaffold_local(
                profile=args.profile,
                topology=args.topology,
                repo=args.repo,
                force=args.force,
            )
            if args.output == "json":
                print(json.dumps(res, indent=2, sort_keys=True))
            else:
                print(f"Created: {res['created']} | Skipped: {res['skipped']} | Instance: {res['instance_local']}")
            return 0

        if args.command == "ensure-branches":
            repo = resolve_repo(args.repo)
            topology = resolve_topology(repo, args.topology)
            if not args.dry_run and not args.yes:
                if is_unattended_agent_env() or not sys.stdin.isatty():
                    print("Pass --yes to create missing branches on GitHub (or run interactively / pass --dry-run).", file=sys.stderr)
                    return 2
                preview = ensure_branches(
                    repo=repo,
                    topology=topology,
                    default_branch=args.default_branch,
                    dry_run=True,
                )
                if not preview["created"]:
                    if args.output == "json":
                        print(json.dumps(preview, indent=2, sort_keys=True))
                    else:
                        print(format_branches_summary(preview, dry_run=False))
                    return 0
                missing_list = ", ".join(preview["created"])
                print(f"{repo} ({topology}): missing {missing_list}", file=interactive_output)
                if not confirm_interactive(f"Create {missing_list} on {repo}?", yes=False):
                    print("Cancelled.", file=interactive_output)
                    return 1
            res = ensure_branches(
                repo=repo,
                topology=topology,
                default_branch=args.default_branch,
                dry_run=args.dry_run,
            )
            if args.output == "json":
                print(json.dumps(res, indent=2, sort_keys=True))
            else:
                print(format_branches_summary(res, dry_run=args.dry_run))
            return 0

        if args.command == "fork":
            upstream = resolve_upstream(args.upstream)
            if not args.dry_run and not args.yes:
                if is_unattended_agent_env() or not sys.stdin.isatty():
                    print("Pass --yes to fork on GitHub (or run interactively / pass --dry-run).", file=sys.stderr)
                    return 2
                preview = fork_repository(upstream=upstream, dry_run=True)
                if not confirm_interactive(f"Fork {upstream} -> {preview['fork']}?", yes=False):
                    print("Cancelled.", file=interactive_output)
                    return 1
            res = fork_repository(upstream=upstream, dry_run=args.dry_run)
            if args.output == "json":
                print(json.dumps(res, indent=2, sort_keys=True))
            else:
                print(f"Fork: {res['fork']} (upstream={res['upstream']})")
            return 0

        if args.command == "enable-actions":
            repo = resolve_repo(args.repo)
            if not args.dry_run and not args.yes:
                if is_unattended_agent_env() or not sys.stdin.isatty():
                    print("Pass --yes to enable GitHub Actions (or run interactively / pass --dry-run).", file=sys.stderr)
                    return 2
                preview = enable_actions(repo=repo, dry_run=True)
                if preview["already_enabled"]:
                    if args.output == "json":
                        print(json.dumps(preview, indent=2, sort_keys=True))
                    else:
                        print(f"{repo}: GitHub Actions already enabled.")
                    return 0
                if not confirm_interactive(f"Enable GitHub Actions on {repo}?", yes=False):
                    print("Cancelled.", file=interactive_output)
                    return 1
            res = enable_actions(repo=repo, dry_run=args.dry_run)
            if args.output == "json":
                print(json.dumps(res, indent=2, sort_keys=True))
            else:
                if res["already_enabled"]:
                    print(f"{res['repo']}: GitHub Actions already enabled.")
                elif args.dry_run:
                    print(f"{res['repo']}: would enable GitHub Actions.")
                else:
                    print(f"{res['repo']}: GitHub Actions enabled.")
            return 0

        if args.command == "apply-event-policy":
            repo = resolve_repo(args.repo)
            if not args.dry_run and not args.yes:
                if is_unattended_agent_env() or not sys.stdin.isatty():
                    print("Pass --yes to apply the Actions event policy (or run interactively / pass --dry-run).", file=sys.stderr)
                    return 2
                if not confirm_interactive(f"Apply the Actions event policy on {repo}?", yes=False):
                    print("Cancelled.", file=interactive_output)
                    return 1
            res = apply_event_policy(repo=repo, dry_run=args.dry_run)
            if args.output == "json":
                print(json.dumps(res, indent=2, sort_keys=True))
            elif res["already_applied"]:
                print(f"{res['repo']}: Actions event policy already applied.")
            elif args.dry_run:
                print(f"{res['repo']}: would apply the Actions event policy ({res['state']}).")
            else:
                print(f"{res['repo']}: Actions event policy applied.")
            return 0

        if args.command == "verify":
            probe = probe_environment(repo=args.repo, offline=args.offline)
            report = verify_profile(probe, profile=args.profile, topology=args.topology, live=not args.offline)
            if args.output == "json":
                print(json.dumps(report, indent=2, sort_keys=True))
            else:
                _print_verify_text(report)
            return 0 if report["ready"] else 1

        if args.command == "topology":
            print(json.dumps(TOPOLOGY_BRANCHES[args.name]))
            return 0

        if args.command == "wizard":
            from wizard import run_wizard

            return run_wizard(args)
    except (ValueError, PermissionError, RuntimeError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
