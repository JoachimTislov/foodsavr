#!/usr/bin/env python3
"""Regenerate doc/integrations scope README indexes from entry frontmatter.

Usage: scripts/docs/integration_index.py [--check]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2] / "doc" / "integrations"
FIELDS = ("id", "name", "scope", "category", "access", "fit", "last_verified")


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError(f"{path}: missing frontmatter")
    meta = {}
    for line in match.group(1).splitlines():
        if ":" in line and not line.startswith(" "):
            key, value = line.split(":", 1)
            meta[key.strip()] = value.split(" #")[0].strip()
    missing = [f for f in FIELDS if not meta.get(f)]
    if missing:
        raise ValueError(f"{path}: missing {', '.join(missing)}")
    return meta


def render(scope_dir):
    rows = []
    for entry in sorted(scope_dir.rglob("*.md")):
        if entry.name == "README.md":
            continue
        meta = frontmatter(entry)
        rel = entry.relative_to(scope_dir).as_posix()
        access = ", ".join(a.strip() for a in meta["access"].strip("[]").split(","))
        rows.append((meta["category"], meta["name"], rel, access, meta["fit"]))
    lines = [
        f"# Integrations: `{scope_dir.name}`",
        "",
        "Generated by `scripts/docs/integration_index.py`; do not edit by hand. "
        "Standard: [../README.md](../README.md).",
        "",
        "| Category | Service | Access | Fit |",
        "|---|---|---|---|",
    ]
    lines += [f"| {c} | [{n}]({p}) | {a} | {f} |" for c, n, p, a, f in sorted(rows)]
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for scope_dir in sorted(p for p in ROOT.iterdir() if p.is_dir()):
        target = scope_dir / "README.md"
        content = render(scope_dir)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target))
        else:
            target.write_text(content, encoding="utf-8")
    if stale:
        print("Stale integration indexes; run scripts/docs/integration_index.py:")
        print("\n".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
