"""Canonical skill catalog and per-harness projections.

`.agents/skills/<name>/SKILL.md` is the single source. Everything else is derived:

- `.claude/skills/` (Claude Code, OpenCode, Copilot): per-file symlinks for every skill.
- `.gemini/skills/`: per-file symlinks for agent skills; `.gemini/commands/<name>.toml`
  wrappers expose human skills as slash commands.
- `agents/openai.yaml` policy (Codex, Vibe): implicit invocation disabled for human skills.
- `.agents/skills/README.md`: the generated catalog, split by audience.

Codex, Vibe, and Copilot also read `.agents/skills/` natively. Every harness loads only
names and descriptions up front; a skill body loads when the skill is invoked.
"""

from __future__ import annotations

import os
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
AUDIENCES = {"agent", "human"}
HARNESS_COMMANDS = {"clear", "compact"}
GENERATED = "Generated by `scripts/agents/agentctl skills sync`; edit `.agents/skills/<name>/SKILL.md` instead."
SKIP_PROJECTION = {"agents"}


@dataclass
class Skill:
    name: str
    path: Path
    fields: dict[str, str] = field(default_factory=dict)
    metadata: dict[str, str] = field(default_factory=dict)
    body: str = ""

    @property
    def audience(self) -> str:
        return self.metadata.get("audience", "")

    @property
    def description(self) -> str:
        return self.fields.get("description", "")

    @property
    def interactive(self) -> bool:
        return self.metadata.get("interactive", "false") == "true"

    @property
    def user_only(self) -> bool:
        return self.fields.get("disable-model-invocation", "false") == "true"


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        inner = value[1:-1]
        return inner.replace('\\"', '"') if value[0] == '"' else inner
    return value


def parse_skill(path: Path) -> Skill:
    """Parse the frontmatter subset skills use: scalars plus a one-level `metadata` map."""
    text = path.read_text(encoding="utf-8")
    skill = Skill(name=path.parent.name, path=path)
    if not text.startswith("---\n"):
        return skill
    end = text.find("\n---", 4)
    if end < 0:
        return skill
    block, skill.body = text[4:end], text[end + 4:]
    section = None
    for line in block.splitlines():
        if not line.strip():
            continue
        if not line.startswith(" "):
            key, _, value = line.partition(":")
            section = key.strip() if not value.strip() else None
            if value.strip():
                skill.fields[key.strip()] = unquote(value)
        elif section == "metadata" and line.startswith("  ") and not line.startswith("   "):
            key, _, value = line.strip().partition(":")
            if value.strip():
                skill.metadata[key.strip()] = unquote(value)
    return skill


def discover(root: Path) -> list[Skill]:
    base = root / ".agents/skills"
    return [parse_skill(path) for path in sorted(base.glob("*/SKILL.md"))]


def referenced_skills(text: str) -> set[str]:
    # Skill mentions: bold slash invocations, "`name` skill", and Skill-tool calls.
    names = set(re.findall(r"\*\*`/([a-z][a-z0-9-]*)`\*\*", text))
    names.update(re.findall(r"`/?([a-z][a-z0-9-]*)` skill\b", text))
    for sentence in re.findall(r"Skill tool[^.\n]*", text):
        names.update(re.findall(r'"([a-z][a-z0-9-]*)"', sentence))
    return names - HARNESS_COMMANDS


def openai_policy_disabled(skill: Skill) -> bool:
    path = skill.path.parent / "agents/openai.yaml"
    return path.exists() and re.search(r"allow_implicit_invocation:\s*false", path.read_text(encoding="utf-8")) is not None


def validation_errors(root: Path, skills: list[Skill] | None = None) -> list[str]:
    skills = discover(root) if skills is None else skills
    names = {skill.name for skill in skills}
    errors = []
    for skill in skills:
        where = skill.path.relative_to(root)
        if skill.fields.get("name") != skill.name:
            errors.append(f"{where}: name must equal directory name {skill.name}")
        if not NAME_RE.fullmatch(skill.name):
            errors.append(f"{where}: name must match {NAME_RE.pattern}")
        if not skill.description or len(skill.description) > 1024:
            errors.append(f"{where}: description must be 1-1024 characters")
        if skill.audience not in AUDIENCES:
            errors.append(f"{where}: metadata.audience must be agent or human")
        if skill.audience == "human" and not skill.user_only:
            errors.append(f"{where}: human skills set disable-model-invocation: true")
        if skill.audience == "agent" and skill.user_only:
            errors.append(f"{where}: agent skills must stay model-invocable")
        if skill.audience == "human" and skill.interactive:
            errors.append(f"{where}: metadata.interactive applies to agent skills only")
        if "paths" in skill.metadata and (skill.audience != "agent" or not skill.metadata["paths"].strip()):
            errors.append(f"{where}: metadata.paths needs a glob list on an agent skill")
        for document in sorted(skill.path.parent.rglob("*.md")):
            for name in sorted(referenced_skills(document.read_text(encoding="utf-8")) - names):
                errors.append(f"{document.relative_to(root)}: references unknown skill {name}")
    return errors


def workflow_skill_errors(root: Path, requested: list[str]) -> list[str]:
    """Headless workflows may only load autonomous agent skills."""
    catalog = {skill.name: skill for skill in discover(root)}
    errors = []
    for name in requested:
        skill = catalog.get(name)
        if skill is None:
            errors.append(f"unknown skill: {name}")
        elif skill.audience != "agent":
            errors.append(f"skill {name} is human-invoked and cannot run in a workflow")
        elif skill.interactive:
            errors.append(f"skill {name} needs a human in the loop and cannot run in a workflow")
    return errors


def toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gemini_command(skill: Skill) -> str:
    return (
        f"# {GENERATED.replace('<name>', skill.name)}\n"
        f"description = {toml_string(skill.description)}\n"
        f'prompt = """Read .agents/skills/{skill.name}/SKILL.md and follow it.\n\nArguments: {{{{args}}}}\n"""\n'
    )


def openai_yaml(skill: Skill, current: str | None) -> str | None:
    """Return the Codex/Vibe metadata with an audience-consistent policy, or None for no file."""
    lines = (current or "").splitlines()
    kept, skipping = [], False
    for line in lines:
        if line.startswith("policy:"):
            skipping = True
            continue
        if skipping and line.startswith(" "):
            continue
        skipping = False
        kept.append(line)
    if skill.audience == "human":
        if not any(line.startswith("interface:") for line in kept):
            title = " ".join(part.capitalize() for part in skill.name.split("-"))
            short = skill.description.split(". ")[0].rstrip(".")
            if len(short) > 64:
                short = short[:61].rsplit(" ", 1)[0] + "..."
            kept = ["interface:", f"  display_name: {toml_string(title)}", f"  short_description: {toml_string(short)}"]
        kept += ["policy:", "  allow_implicit_invocation: false"]
    if not kept:
        return None
    return "\n".join(kept) + "\n"


LINK_RE = re.compile(r"\]\(([^)\s#]+)(#[^)]*)?\)")


def relink(text: str, source_dir: Path, target_dir: Path) -> str:
    """Rewrite relative Markdown links so they resolve from a copied location."""
    def replace(match: re.Match[str]) -> str:
        target, anchor = match.group(1), match.group(2) or ""
        if "://" in target or target.startswith(("/", "mailto:")):
            return match.group(0)
        return f"]({os.path.relpath(source_dir / target, target_dir)}{anchor})"
    return LINK_RE.sub(replace, text)


def copilot_instructions(root: Path, skill: Skill) -> str:
    """Path-scoped Copilot instructions: the skill body, loaded only for matching files."""
    target_dir = root / ".github/instructions"
    body = relink(skill.body.lstrip("\n"), skill.path.parent, target_dir)
    return (
        f"---\napplyTo: {toml_string(skill.metadata['paths'])}\n---\n\n"
        f"<!-- {GENERATED.replace('<name>', skill.name)} -->\n\n{body}"
    )


def copilot_root(skills: list[Skill]) -> str:
    scoped = [skill for skill in skills if skill.metadata.get("paths")]
    lines = [
        "# FoodSavr Copilot instructions", "",
        "<!-- Generated by `scripts/agents/agentctl skills sync` from skill `metadata.paths`; edit AGENTS.md or the skills instead. -->", "",
        "Repository rules are in [AGENTS.md](../AGENTS.md); it is the canonical always-loaded context and wins over anything here.", "",
        "Path-scoped standards load only for matching files:", "",
    ]
    lines += [f"- [{skill.name}](instructions/{skill.name}.instructions.md): `{skill.metadata['paths']}`" for skill in scoped]
    lines += ["", "Other skills: [.agents/skills/README.md](../.agents/skills/README.md).", ""]
    return "\n".join(lines)


def catalog(skills: list[Skill]) -> str:
    agent = [skill for skill in skills if skill.audience == "agent"]
    human = [skill for skill in skills if skill.audience == "human"]
    out = [
        "# Skills", "", f"<!-- {GENERATED} -->", "",
        "Canonical source for every harness. Bodies load lazily: harnesses keep only names and descriptions in context until a skill is invoked.", "",
        "## Agent skills", "",
        "Model-invoked: an agent loads them when a task matches, in any harness, locally, in T3 Code, or on a GitHub runner. Interactive ones need a human in the loop and are rejected by headless workflows.", "",
        "| Skill | Use | Interactive |", "|---|---|---|",
    ]
    out += [f"| [{s.name}]({s.name}/SKILL.md) | {s.description.replace('|', '/')} | {'yes' if s.interactive else ''} |" for s in agent]
    out += [
        "", "## Human skills", "",
        "User-invoked only (`disable-model-invocation`; Codex/Vibe `allow_implicit_invocation: false`): zero context load until a person types the name. Start with `/skills-guide`.", "",
        "| Invoke | Use |", "|---|---|",
    ]
    out += [f"| [`/{s.name}`]({s.name}/SKILL.md) | {s.description.replace('|', '/')} |" for s in human]
    out += [
        "", "## Harness projections", "",
        "| Harness | Discovers | Human skills |", "|---|---|---|",
        "| Codex, Vibe | `.agents/skills/` | `agents/openai.yaml` policy |",
        "| Claude Code, OpenCode | `.claude/skills/` (symlinks) | `disable-model-invocation` |",
        "| Copilot | `.agents/skills/`, `.claude/skills/` | `disable-model-invocation` |",
        "| Gemini | `.gemini/skills/` (agent skills) | `.gemini/commands/<name>.toml` |",
        "| Copilot code review | `.github/instructions/<name>.instructions.md` for skills with `metadata.paths` | not projected |",
        "", "Always-loaded context is `AGENTS.md` only; `CLAUDE.md` and `GEMINI.md` are symlinks to it, and `.github/copilot-instructions.md` is a generated pointer.", "",
    ]
    return "\n".join(out)


def expected_state(root: Path, skills: list[Skill]) -> dict[Path, tuple[str, str]]:
    """Map each derived path to ("link", target) or ("file", content)."""
    state: dict[Path, tuple[str, str]] = {}
    for skill in skills:
        source_dir = skill.path.parent
        targets = [(".claude/skills", True), (".gemini/skills", skill.audience == "agent")]
        for files in sorted(source_dir.rglob("*")):
            relative = files.relative_to(source_dir)
            if files.is_dir() or relative.parts[0] in SKIP_PROJECTION:
                continue
            for projection, wanted in targets:
                if wanted:
                    link = root / projection / skill.name / relative
                    state[link] = ("link", os.path.relpath(files, link.parent))
        if skill.audience == "human":
            state[root / ".gemini/commands" / f"{skill.name}.toml"] = ("file", gemini_command(skill))
        if skill.audience == "agent" and skill.metadata.get("paths"):
            state[root / ".github/instructions" / f"{skill.name}.instructions.md"] = ("file", copilot_instructions(root, skill))
        yaml_path = source_dir / "agents/openai.yaml"
        current = yaml_path.read_text(encoding="utf-8") if yaml_path.exists() else None
        desired = openai_yaml(skill, current)
        if desired is not None:
            state[yaml_path] = ("file", desired)
    state[root / ".agents/skills/README.md"] = ("file", catalog(skills))
    state[root / ".github/copilot-instructions.md"] = ("file", copilot_root(skills))
    return state


MANAGED_DIRS = (".claude/skills", ".gemini/skills", ".gemini/commands", ".github/instructions")


def drift(root: Path, skills: list[Skill]) -> list[str]:
    state = expected_state(root, skills)
    problems = []
    for path, (kind, value) in sorted(state.items()):
        relative = path.relative_to(root)
        if kind == "link":
            if not path.is_symlink() or os.readlink(path) != value:
                problems.append(f"{relative}: projection missing or stale")
        elif not path.exists() or path.is_symlink() or path.read_text(encoding="utf-8") != value:
            problems.append(f"{relative}: generated file missing or stale")
    for managed in MANAGED_DIRS:
        for path in sorted((root / managed).rglob("*")) if (root / managed).exists() else []:
            if (path.is_symlink() or path.is_file()) and path not in state:
                problems.append(f"{path.relative_to(root)}: not derived from a skill")
    return problems


def sync(root: Path, skills: list[Skill]) -> list[str]:
    for managed in MANAGED_DIRS:
        shutil.rmtree(root / managed, ignore_errors=True)
    written = []
    for path, (kind, value) in sorted(expected_state(root, skills).items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        if kind == "link":
            path.symlink_to(value)
        else:
            if path.exists() and not path.is_symlink() and path.read_text(encoding="utf-8") == value:
                continue
            path.write_text(value, encoding="utf-8")
        written.append(str(path.relative_to(root)))
    return written


def context_errors(root: Path) -> list[str]:
    """AGENTS.md is the one always-loaded file; harness entrypoints must resolve to it."""
    errors = []
    agents = root / "AGENTS.md"
    if not agents.is_file() or agents.is_symlink():
        errors.append("AGENTS.md: must be a regular file")
    for name in ("CLAUDE.md", "GEMINI.md"):
        path = root / name
        if not path.is_symlink() or os.readlink(path) != "AGENTS.md":
            errors.append(f"{name}: must be a symlink to AGENTS.md")
    if agents.is_file():
        for target in re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", agents.read_text(encoding="utf-8")):
            if "://" not in target and not (root / target).exists():
                errors.append(f"AGENTS.md: broken link {target}")
    return errors
